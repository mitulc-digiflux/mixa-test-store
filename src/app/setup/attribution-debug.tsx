"use client";

import { useEffect, useState } from "react";
import { readAttribution, waitForSdk, type ClientAttribution } from "@/lib/mixa-client";

const STORAGE_KEYS = ["mixa_clickId", "mixa_clickId_ts", "mixa_clickid", "mixa_clickid_ts"];

export function AttributionDebug({ sampleUrl }: { sampleUrl: string }) {
  const [sdk, setSdk] = useState<"loading" | "yes" | "no">("loading");
  const [a, setA] = useState<ClientAttribution | null>(null);

  async function refresh() {
    setSdk((await waitForSdk()) ? "yes" : "no");
    setA(await readAttribution());
  }

  useEffect(() => {
    let live = true;
    (async () => {
      const found = await waitForSdk();
      const attribution = await readAttribution();
      if (!live) return;
      setSdk(found ? "yes" : "no");
      setA(attribution);
    })();
    return () => {
      live = false;
    };
  }, []);

  function openFakeLink() {
    // Fake click IDs prove the script saves the ID. mixa will not pay
    // commission on them: the click has to exist on mixa's side.
    const id = `mxTEST${Math.random().toString(36).slice(2, 12)}`;
    // Full page load on purpose: the SDK reads the click ID when a page lands.
    // eslint-disable-next-line @next/next/no-location-assign-relative-destination
    location.href = `${sampleUrl}&utm_source=mixa&mixa_clickId=${id}`;
  }

  function clear() {
    for (const k of STORAGE_KEYS) {
      document.cookie = `${k}=; Max-Age=0; path=/`;
      try {
        localStorage.removeItem(k);
      } catch {}
    }
    refresh();
  }

  return (
    <div className="flex flex-col gap-2 rounded-lg border border-stone-200 bg-white p-4 text-sm">
      <p>
        SDK on this page:{" "}
        <b className={sdk === "yes" ? "text-emerald-700" : sdk === "no" ? "text-red-700" : ""}>
          {sdk === "loading" ? "checking…" : sdk === "yes" ? "loaded (window.mixaSDK)" : "not found"}
        </b>
      </p>
      <pre className="overflow-x-auto rounded bg-stone-100 p-3 text-xs">
        {a ? JSON.stringify(a, null, 2) : "…"}
      </pre>
      <div className="flex flex-wrap gap-2">
        <button onClick={openFakeLink} className="rounded-md bg-stone-900 px-3 py-1.5 text-white">
          Open fake creator link
        </button>
        <button onClick={clear} className="rounded-md border border-stone-300 px-3 py-1.5">
          Clear saved click ID
        </button>
        <button onClick={refresh} className="rounded-md border border-stone-300 px-3 py-1.5">
          Re-read
        </button>
      </div>
      <p className="text-xs text-stone-500">
        The fake link only checks that the script saves the click ID. For a real commission test,
        open a creator link generated by mixa for one of your uploaded products.
      </p>
    </div>
  );
}
